"""The twelve tables of the brief's Services section, created if missing on every start."""

from .db import Tx

DDL = """
CREATE TABLE IF NOT EXISTS accounts (
  id text PRIMARY KEY,
  email text NOT NULL,
  name text NOT NULL,
  role text NOT NULL CHECK (role IN ('maker', 'licence_reviewer', 'access_reviewer', 'lead', 'auditor')),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE UNIQUE INDEX IF NOT EXISTS accounts_email_key ON accounts (lower(email));

CREATE TABLE IF NOT EXISTS sessions (
  token_hash text PRIMARY KEY,
  account_id text NOT NULL REFERENCES accounts (id),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS login_failures (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  email text NOT NULL,
  failed_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS login_failures_email ON login_failures (email, failed_at);

CREATE TABLE IF NOT EXISTS objects (
  id integer PRIMARY KEY,
  title text NOT NULL UNIQUE,
  image_title text,
  page_url text,
  article_url text,
  description text,
  extract text,
  license text NOT NULL,
  license_url text,
  artist text NOT NULL DEFAULT '',
  image_desc_url text,
  width integer NOT NULL CHECK (width > 0),
  height integer NOT NULL CHECK (height > 0),
  cutout_id text NOT NULL,
  mask_w integer NOT NULL,
  mask_h integer NOT NULL,
  mask_b integer NOT NULL,
  shuffle_rank integer NOT NULL UNIQUE
);
CREATE INDEX IF NOT EXISTS objects_cutout ON objects (cutout_id);
CREATE INDEX IF NOT EXISTS objects_license ON objects (license);

CREATE TABLE IF NOT EXISTS pieces (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  summary text NOT NULL,
  fee_cents integer NOT NULL CHECK (fee_cents BETWEEN 0 AND 500000),
  submitted_fee_cents integer NOT NULL CHECK (submitted_fee_cents BETWEEN 0 AND 500000),
  state text NOT NULL CHECK (state IN ('draft', 'submitted', 'in_review', 'changes_requested', 'cleared',
                                      'scheduled', 'published', 'withdrawn', 'rejected')),
  owner_id text NOT NULL REFERENCES accounts (id),
  version integer NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  published_at timestamptz,
  cleared_at timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS pieces_live_title ON pieces (lower(title)) WHERE state <> 'rejected';
CREATE INDEX IF NOT EXISTS pieces_cleared_at ON pieces (cleared_at);

CREATE TABLE IF NOT EXISTS piece_objects (
  piece_id bigint NOT NULL REFERENCES pieces (id),
  object_id integer NOT NULL REFERENCES objects (id),
  position integer NOT NULL,
  PRIMARY KEY (piece_id, object_id)
);

CREATE TABLE IF NOT EXISTS reviews (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  piece_id bigint NOT NULL REFERENCES pieces (id),
  kind text NOT NULL CHECK (kind IN ('licence', 'accessibility')),
  reviewer_id text NOT NULL REFERENCES accounts (id),
  result text NOT NULL CHECK (result IN ('pass', 'fail')),
  reason text,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  UNIQUE (piece_id, kind)
);

CREATE TABLE IF NOT EXISTS duplicate_acks (
  piece_id bigint NOT NULL REFERENCES pieces (id),
  object_id integer NOT NULL REFERENCES objects (id),
  duplicate_object_id integer NOT NULL REFERENCES objects (id),
  acknowledged_by text NOT NULL REFERENCES accounts (id),
  acknowledged_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  PRIMARY KEY (piece_id, object_id, duplicate_object_id)
);

CREATE TABLE IF NOT EXISTS schedule_slots (
  day date NOT NULL UNIQUE,
  piece_id bigint NOT NULL UNIQUE REFERENCES pieces (id),
  view_count integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS budgets (
  quarter text PRIMARY KEY CHECK (quarter ~ '^[0-9]{4}-Q[1-4]$'),
  budget_cents integer NOT NULL CHECK (budget_cents >= 0)
);

CREATE TABLE IF NOT EXISTS audit_entries (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  piece_id bigint NOT NULL REFERENCES pieces (id),
  actor_id text NOT NULL REFERENCES accounts (id),
  from_state text,
  to_state text NOT NULL,
  reason text,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX IF NOT EXISTS audit_piece ON audit_entries (piece_id, created_at);
CREATE INDEX IF NOT EXISTS audit_created ON audit_entries (created_at, id);

CREATE TABLE IF NOT EXISTS preferences (
  account_id text PRIMARY KEY REFERENCES accounts (id),
  rows_per_page integer NOT NULL DEFAULT 50 CHECK (rows_per_page IN (25, 50, 100)),
  date_display text NOT NULL DEFAULT 'relative' CHECK (date_display IN ('relative', 'absolute')),
  high_contrast boolean NOT NULL DEFAULT false
);
"""


def create(tx: Tx) -> None:
    for statement in DDL.split(";"):
        if statement.strip():
            tx.run(statement)
