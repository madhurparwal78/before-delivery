def busy_wait_until(predicate: Callable[[], bool], what: str, seconds: float) -> None:
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        if predicate():
            return
    pytest.fail(what)


def eventually(page: Page | None, check: Callable[[], Any], what: str, seconds: float = WAIT_S,
               step_ms: float = STEP_MS) -> Any:
    deadline = time.monotonic() + seconds
    last: Any = None
    while time.monotonic() < deadline:
        try:
            last = check()
            if last:
                return last
        except (PlaywrightError, AssertionError, httpx.HTTPError, KeyError, ValueError, TypeError) as exc:
            last = exc
        if page is not None and step_ms:
            advance(page, step_ms)
    pytest.fail(f"{what} (last seen: {last!r})")


def within_parse(page: Page, check: Callable[[], Any], what: str) -> None:
    spent = 0
    budget = PARSE_DELAY_MS + RENDER_SLACK_MS
    while spent < budget:
        advance(page, 25)
        spent += 25
        with contextlib.suppress(PlaywrightError):
            if check():
                return
    deadline = time.monotonic() + 5
    while time.monotonic() < deadline:
        with contextlib.suppress(PlaywrightError):
            if check():
                return
    pytest.fail(f"{what} within {PARSE_DELAY_MS} ms of page time (L287)")


