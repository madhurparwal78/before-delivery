import { build } from "esbuild";
import {
  mkdir,
  readFile,
  writeFile,
  copyFile,
  readdir,
} from "node:fs/promises";
import { createHash } from "node:crypto";
const fontRows = [
  ["newsreader", [400, 500]],
  ["instrument-sans", [400, 500, 600]],
  ["jetbrains-mono", [400, 600]],
] as const;
await mkdir("public/fonts", { recursive: true });
await mkdir("dist", { recursive: true });
await mkdir("public/dist", { recursive: true });
const assets: {
  path: string;
  sha256: string;
  source: string;
  licence: string;
}[] = [];
const fontNotices: string[] = [];
for (const [family, weights] of fontRows) {
  for (const weight of weights) {
    const name = `${family}-latin-${weight}-normal.woff2`;
    const src = `node_modules/@fontsource/${family}/files/${name}`;
    const target = `public/fonts/${name}`;
    await copyFile(src, target);
    const bytes = await readFile(target);
    assets.push({
      path: target,
      sha256: createHash("sha256").update(bytes).digest("hex"),
      source: `https://www.npmjs.com/package/@fontsource/${family}/v/5.3.0`,
      licence: "OFL-1.1",
    });
  }
  fontNotices.push(
    `## ${family} — OFL-1.1\n\n${await readFile(`node_modules/@fontsource/${family}/LICENSE`, "utf8")}`,
  );
}
await writeFile("assets.json", JSON.stringify(assets, null, 2) + "\n");
const notices: string[] = [
  "pg-native is an optional peer of pg. It is not installed, bundled or used by this application. Only the pure TypeScript/JavaScript PostgreSQL driver ships.",
  "# Third-party notices\n\nAll sample WAV, PNG and PDF bytes are procedurally generated by src/media.ts; original Aldermoor Open Record code. Lucide inline icon paths: ISC, Copyright (c) Lucide Contributors.\n",
];
async function packages(dir: string): Promise<void> {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name.startsWith(".")) continue;
    const path = dir + "/" + entry.name;
    if (entry.name.startsWith("@")) {
      await packages(path);
      continue;
    }
    let meta: {
      name: string;
      version: string;
      license?: string;
      licenses?: { type: string }[];
      author?: string | { name?: string };
    };
    try {
      meta = JSON.parse(
        await readFile(path + "/package.json", "utf8"),
      ) as typeof meta;
    } catch {
      continue;
    }
    let text = "";
    const files = await readdir(path);
    for (const file of files.filter((n) =>
      /^licen[sc]e(?:\.|$)|^copying$|^notice(?:\.|$)|^thirdpartynoticetext\.txt$/i.test(
        n,
      ),
    )) {
      text += await readFile(path + "/" + file, "utf8");
    }
    const owner =
      typeof meta.author === "string" ? meta.author : meta.author?.name;
    const copyright = owner
      ? `Copyright attribution: ${owner}${owner.endsWith(".") ? "" : "."}`
      : text
          .split(/\r?\n/)
          .find((line) =>
            /^\s*copyright\s+(?:(?:\(c\)|©)\s*)?\d{4}/i.test(line),
          ) || `Copyright ${meta.name} contributors.`;
    notices.push(
      `## ${meta.name} ${meta.version}\n\nLicence: ${meta.license || meta.licenses?.map((item) => item.type).join(" OR ") || "See license text"}.\n\n${copyright}\n\n${text || `Copyright ${typeof meta.author === "string" ? meta.author : meta.author?.name || meta.name + " contributors"}.`}`,
    );
    try {
      await packages(path + "/node_modules");
    } catch {}
  }
}
await packages("node_modules");
notices.push(...fontNotices);
await writeFile("THIRD_PARTY_NOTICES.md", notices.join("\n\n"));
await build({
  entryPoints: ["src/server.ts"],
  bundle: true,
  platform: "node",
  target: "node22",
  format: "esm",
  outfile: "dist/server.js",
  external: ["pg-native"],
  banner: {
    js: 'import { createRequire } from "node:module"; const require = createRequire(import.meta.url);',
  },
});
await build({
  entryPoints: ["src/browser.ts"],
  bundle: true,
  platform: "browser",
  target: ["chrome120", "firefox120", "safari17"],
  format: "esm",
  outfile: "public/dist/browser.js",
});
