// The PostgreSQL schema, applied idempotently on every start. All instants are epoch milliseconds.

export const SCHEMA = `
CREATE TABLE IF NOT EXISTS app_meta (
  key text PRIMARY KEY,
  value text NOT NULL
);

CREATE TABLE IF NOT EXISTS accounts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL,
  email_lower text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  display_name text NOT NULL,
  time_zone text NOT NULL,
  verified boolean NOT NULL DEFAULT false,
  role text NOT NULL CHECK (role IN ('islander', 'operator')),
  trophies integer NOT NULL DEFAULT 0 CHECK (trophies >= 0),
  created_at bigint NOT NULL
);

CREATE TABLE IF NOT EXISTS sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash text NOT NULL UNIQUE,
  csrf_token text NOT NULL,
  account_id bigint REFERENCES accounts(id),
  created_at bigint NOT NULL,
  signed_in_at bigint,
  ended_at bigint
);
CREATE INDEX IF NOT EXISTS sessions_live_account ON sessions (account_id) WHERE ended_at IS NULL;

CREATE TABLE IF NOT EXISTS email_links (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id bigint NOT NULL REFERENCES accounts(id),
  kind text NOT NULL CHECK (kind IN ('confirm', 'reset')),
  token_hash text NOT NULL UNIQUE,
  issued_at bigint NOT NULL,
  used_at bigint,
  superseded_at bigint
);
CREATE INDEX IF NOT EXISTS email_links_account ON email_links (account_id, kind);

CREATE TABLE IF NOT EXISTS throttle_hits (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  limit_key text NOT NULL,
  at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS throttle_hits_key ON throttle_hits (limit_key, at);

CREATE TABLE IF NOT EXISTS mail_queue (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient text NOT NULL,
  subject text NOT NULL,
  body text NOT NULL,
  created_at bigint NOT NULL,
  lease_until bigint,
  sent_at bigint,
  attempts integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS mail_queue_waiting ON mail_queue (id) WHERE sent_at IS NULL;

CREATE TABLE IF NOT EXISTS villages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id bigint NOT NULL UNIQUE REFERENCES accounts(id),
  created_at bigint NOT NULL,
  shield_start bigint,
  shield_end bigint
);

CREATE TABLE IF NOT EXISTS buildings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  village_id bigint NOT NULL REFERENCES villages(id),
  type text NOT NULL,
  x integer NOT NULL,
  y integer NOT NULL,
  rotation integer NOT NULL CHECK (rotation IN (0, 90, 180, 270)),
  level integer NOT NULL CHECK (level BETWEEN 0 AND 3),
  job_to_level integer,
  job_started_at bigint,
  job_finishes_at bigint,
  job_cost jsonb,
  accrual_start bigint NOT NULL,
  created_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS buildings_village ON buildings (village_id);

CREATE TABLE IF NOT EXISTS training_batches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  village_id bigint NOT NULL REFERENCES villages(id),
  unit text NOT NULL,
  count integer NOT NULL CHECK (count BETWEEN 1 AND 20),
  cost jsonb NOT NULL,
  enqueued_at bigint NOT NULL,
  starts_at bigint NOT NULL,
  finishes_at bigint NOT NULL,
  state text NOT NULL CHECK (state IN ('queued', 'done', 'cancelled'))
);
CREATE INDEX IF NOT EXISTS training_batches_village ON training_batches (village_id) WHERE state = 'queued';

CREATE SEQUENCE IF NOT EXISTS ledger_pair_ids;

CREATE TABLE IF NOT EXISTS ledger_entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pair_id bigint NOT NULL,
  village_id bigint REFERENCES villages(id),
  counterparty_village_id bigint REFERENCES villages(id),
  kind text NOT NULL,
  asset text NOT NULL,
  amount bigint NOT NULL,
  raid_id bigint,
  created_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS ledger_entries_village ON ledger_entries (village_id, asset);
CREATE INDEX IF NOT EXISTS ledger_entries_pair ON ledger_entries (pair_id);

CREATE TABLE IF NOT EXISTS raids (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attacker_village_id bigint NOT NULL REFERENCES villages(id),
  defender_village_id bigint NOT NULL REFERENCES villages(id),
  state text NOT NULL CHECK (state IN ('locked', 'deploying', 'resolved', 'abandoned')),
  end_reason text CHECK (end_reason IN ('finalized', 'deadline_passed')),
  locked_at bigint NOT NULL,
  finalize_by bigint NOT NULL,
  seed bigint NOT NULL,
  layout jsonb NOT NULL,
  army jsonb NOT NULL,
  lootable jsonb NOT NULL,
  deploys jsonb NOT NULL DEFAULT '[]'::jsonb,
  result jsonb,
  tick_hashes jsonb,
  resolved_at bigint
);
CREATE INDEX IF NOT EXISTS raids_open ON raids (finalize_by) WHERE state IN ('locked', 'deploying');
CREATE INDEX IF NOT EXISTS raids_attacker ON raids (attacker_village_id);
CREATE INDEX IF NOT EXISTS raids_defender ON raids (defender_village_id);

CREATE TABLE IF NOT EXISTS reward_claims (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id bigint NOT NULL REFERENCES accounts(id),
  kind text NOT NULL CHECK (kind IN ('daily', 'weekly')),
  claimed_at bigint NOT NULL,
  time_zone text NOT NULL,
  step integer,
  league text
);
CREATE INDEX IF NOT EXISTS reward_claims_account ON reward_claims (account_id, kind, claimed_at);

CREATE TABLE IF NOT EXISTS clans (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  name_lower text NOT NULL,
  motto text NOT NULL,
  created_at bigint NOT NULL,
  dissolved_at bigint
);
CREATE UNIQUE INDEX IF NOT EXISTS clans_live_name ON clans (name_lower) WHERE dissolved_at IS NULL;

CREATE TABLE IF NOT EXISTS clan_members (
  account_id bigint PRIMARY KEY REFERENCES accounts(id),
  clan_id bigint NOT NULL REFERENCES clans(id),
  role text NOT NULL CHECK (role IN ('skipper', 'mate', 'deckhand')),
  joined_at bigint NOT NULL,
  mate_since bigint
);
CREATE INDEX IF NOT EXISTS clan_members_clan ON clan_members (clan_id);

CREATE TABLE IF NOT EXISTS invitations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clan_id bigint NOT NULL REFERENCES clans(id),
  email_lower text NOT NULL,
  inviter_account_id bigint NOT NULL REFERENCES accounts(id),
  state text NOT NULL CHECK (state IN ('pending', 'accepted', 'declined', 'cancelled')),
  created_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS invitations_email ON invitations (email_lower) WHERE state = 'pending';

CREATE TABLE IF NOT EXISTS clan_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clan_id bigint NOT NULL REFERENCES clans(id),
  author_account_id bigint NOT NULL REFERENCES accounts(id),
  body text,
  removed boolean NOT NULL DEFAULT false,
  created_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS clan_messages_clan ON clan_messages (clan_id, id);

CREATE TABLE IF NOT EXISTS donation_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clan_id bigint NOT NULL REFERENCES clans(id),
  requester_account_id bigint NOT NULL REFERENCES accounts(id),
  unit text NOT NULL,
  count integer NOT NULL CHECK (count BETWEEN 1 AND 6),
  state text NOT NULL CHECK (state IN ('open', 'filled', 'closed')),
  created_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS donation_requests_clan ON donation_requests (clan_id, state);

CREATE TABLE IF NOT EXISTS donations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id bigint NOT NULL REFERENCES donation_requests(id),
  clan_id bigint NOT NULL REFERENCES clans(id),
  donor_account_id bigint NOT NULL REFERENCES accounts(id),
  recipient_account_id bigint NOT NULL REFERENCES accounts(id),
  unit text NOT NULL,
  count integer NOT NULL CHECK (count BETWEEN 1 AND 3),
  pair_id bigint NOT NULL,
  created_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS donations_donor ON donations (donor_account_id, created_at);
CREATE INDEX IF NOT EXISTS donations_request ON donations (request_id);

CREATE TABLE IF NOT EXISTS idempotency_records (
  account_id bigint NOT NULL REFERENCES accounts(id),
  method text NOT NULL,
  path text NOT NULL,
  idem_key text NOT NULL,
  request_body jsonb NOT NULL,
  status integer NOT NULL,
  response jsonb NOT NULL,
  created_at bigint NOT NULL,
  PRIMARY KEY (account_id, method, path, idem_key)
);
`;
