def drag(page: Page, start: tuple[float, float], end: tuple[float, float], during: Callable[[], Any] | None = None) -> Any:
    page.mouse.move(*start)
    page.mouse.down()
    for i in range(1, 11):
        page.mouse.move(start[0] + (end[0] - start[0]) * i / 10, start[1] + (end[1] - start[1]) * i / 10)
    seen = during() if during else None
    page.mouse.up()
    return seen


