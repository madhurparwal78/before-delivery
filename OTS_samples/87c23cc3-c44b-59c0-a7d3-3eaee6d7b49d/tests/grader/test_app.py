def touch(cdp: Any, kind: str, points: list[tuple[float, float]]) -> None:
    cdp.send("Input.dispatchTouchEvent", {"type": kind, "touchPoints": [{"x": x, "y": y, "id": i} for i, (x, y) in enumerate(points)]})


def gesture(page: Page, cdp: Any, start: list[tuple[float, float]], end: list[tuple[float, float]]) -> None:
    touch(cdp, "touchStart", start)
    for i in range(1, 11):
        touch(cdp, "touchMove", [(s[0] + (e[0] - s[0]) * i / 10, s[1] + (e[1] - s[1]) * i / 10) for s, e in zip(start, end)])
    touch(cdp, "touchEnd", [])
    advance(page, STEP_MS)


def zoom_percent(page: Page) -> int:
    found = re.fullmatch(r"Zoom (\d+)%", status_text(page, "Zoom"))
    assert found, status_text(page, "Zoom")
    return int(found.group(1))


