// Regenerates assets.json and THIRD_PARTY_NOTICES.md from the lockfile tree, the fonts and the generated seed assets.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sha = (file) => createHash("sha256").update(readFileSync(file)).digest("hex");
const walkFiles = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walkFiles(full) : [full];
  });
const rel = (file) => relative(root, file).split(sep).join("/");

// ---- assets.json ----------------------------------------------------------------------------------------------
const assets = [];
for (const file of walkFiles(join(root, "assets", "seed")).filter((f) => /\.(glb|png)$/.test(f)).sort()) {
  assets.push({ path: rel(file), sha256: sha(file), source: "generated by tools/generate-seed-assets.ts for this app", licence: "original" });
}
const fonts = [
  ["public/fonts/red-hat-display-900.woff2", "https://fontsource.org/fonts/red-hat-display (npm @fontsource/red-hat-display 5.3.0, latin, 900)"],
  ["public/fonts/red-hat-text-400.woff2", "https://fontsource.org/fonts/red-hat-text (npm @fontsource/red-hat-text 5.3.0, latin, 400)"],
  ["public/fonts/red-hat-text-700.woff2", "https://fontsource.org/fonts/red-hat-text (npm @fontsource/red-hat-text 5.3.0, latin, 700)"],
];
for (const [path, source] of fonts) assets.push({ path, sha256: sha(join(root, path)), source, licence: "OFL-1.1" });
writeFileSync(join(root, "assets.json"), JSON.stringify(assets, null, 2) + "\n");

// ---- THIRD_PARTY_NOTICES.md -----------------------------------------------------------------------------------
const tree = JSON.parse(execFileSync("npm", ["ls", "--omit=dev", "--all", "--json"], { cwd: root, encoding: "utf8", maxBuffer: 1 << 26 }));
const found = new Map();
const visit = (node) => {
  for (const [name, dep] of Object.entries(node.dependencies ?? {})) {
    if (dep.version && existsSync(join(root, "node_modules", name, "package.json"))) found.set(`${name}@${dep.version}`, name);
    visit(dep);
  }
};
visit(tree);

const copyrightOf = (dir, manifest) => {
  for (const name of readdirSync(dir)) {
    if (/^licen[cs]e/i.test(name)) {
      const line = readFileSync(join(dir, name), "utf8").split("\n").find((l) => /copyright/i.test(l));
      if (line) return line.trim();
    }
  }
  const author = typeof manifest.author === "string" ? manifest.author : manifest.author?.name;
  return author ? `Copyright (c) ${author}` : "Copyright (c) the package authors";
};

const rows = [...found.keys()].sort().map((key) => {
  const name = found.get(key);
  const dir = join(root, "node_modules", name);
  const manifest = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const licence = typeof manifest.license === "string" ? manifest.license : (manifest.license?.type ?? "see package");
  return `| ${name} | ${manifest.version} | ${licence} | ${copyrightOf(dir, manifest).replace(/\|/g, "/")} |`;
});

const ofl = readFileSync(join(root, "node_modules", "@fontsource", "red-hat-display", "LICENSE"), "utf8");

const text = `# Third-party notices

Highwater Unit Finder ships the packages, fonts, icons and files listed here. Every one is licensed under MIT, ISC,
BSD-2-Clause, BSD-3-Clause, Apache-2.0, 0BSD, CC0-1.0 or OFL-1.1, or was made for this app.

## Production packages

The production dependency tree from \`npm ls --omit=dev --all --json\`.

| Package | Version | Licence | Copyright |
|---|---|---|---|
${rows.join("\n")}

## Fonts

- **Red Hat Display** (weight 900) and **Red Hat Text** (weights 400 and 700), served from \`public/fonts/\`. Licence: SIL Open Font
  License 1.1 (OFL-1.1). Copyright 2024 The Red Hat Project Authors (https://github.com/RedHatOfficial/RedHatFont). Obtained from
  the Fontsource packages @fontsource/red-hat-display and @fontsource/red-hat-text, version 5.3.0.

## Icons

- **Lucide** icons, bundled through the \`lucide-react\` package (ISC licence, listed above). Copyright (c) for Lucide Contributors;
  parts derived from Feather, Copyright (c) 2013-2022 Cole Bemis (MIT).

## Draco decoder

- \`public/draco/draco_decoder.js\`, \`draco_decoder.wasm\` and \`draco_wasm_wrapper.js\`: the Draco mesh decoder that ships with three.js
  (three@0.187.0, examples/jsm/libs/draco), Copyright Google Inc., Apache License 2.0 (Apache-2.0). It decodes the Draco-compressed
  tower models in the browser.

## Media

Every model, texture and photograph under \`assets/seed/\` was generated for this app by \`tools/generate-seed-assets.ts\` (licence:
original, see \`assets.json\`): the tower shell and floor-plate models, the facade and duotone-ramp textures, and the 31 view
photographs. They are written to the object store at first start.

## Build-time tools (not shipped)

TypeScript, esbuild, tsx, @gltf-transform/core, @gltf-transform/extensions and draco3dgltf are used to build the app and to
generate the seed assets; none of them is part of the production dependency tree.

## SIL Open Font License 1.1

${ofl.trim()}
`;
writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), text);
console.log(`assets.json: ${assets.length} entries; notices: ${rows.length} packages`);
