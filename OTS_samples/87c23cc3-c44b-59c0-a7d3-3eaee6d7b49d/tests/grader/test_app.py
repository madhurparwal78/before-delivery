def in_view(page: Page, loc: Locator) -> bool:
    if loc.count() == 0 or not loc.first.is_visible():
        return False
    box = loc.first.bounding_box()
    size = page.viewport_size
    return bool(box) and box["width"] > 0 and box["x"] < size["width"] and box["x"] + box["width"] > 0


