def free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


class Relay:

    def __init__(self, host: str, port: int) -> None:
        self.target = (host, port)
        self.port = free_port()
        self.listener: socket.socket | None = None
        self.conns: list[socket.socket] = []
        self.lock = threading.Lock()

    def start(self) -> None:
        lst = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        lst.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        lst.bind(("127.0.0.1", self.port))
        lst.listen(64)
        self.listener = lst
        threading.Thread(target=self._accept, args=(lst,), daemon=True).start()

    def _accept(self, lst: socket.socket) -> None:
        for _ in range(1_000_000):
            try:
                client, _ = lst.accept()
            except OSError:
                return
            try:
                upstream = socket.create_connection(self.target, timeout=5)
            except OSError:
                client.close()
                continue
            upstream.settimeout(None)
            with self.lock:
                self.conns += [client, upstream]
            threading.Thread(target=self._pipe, args=(client, upstream), daemon=True).start()
            threading.Thread(target=self._pipe, args=(upstream, client), daemon=True).start()

    @staticmethod
    def _pipe(src: socket.socket, dst: socket.socket) -> None:
        for _ in range(10_000_000):
            try:
                data = src.recv(65536)
            except OSError:
                break
            if not data:
                break
            try:
                dst.sendall(data)
            except OSError:
                break
        for s in (src, dst):
            with contextlib.suppress(OSError):
                s.shutdown(socket.SHUT_RDWR)

    def stop(self) -> None:
        if self.listener is not None:
            with contextlib.suppress(OSError):
                self.listener.shutdown(socket.SHUT_RDWR)
            self.listener.close()
            self.listener = None
        with self.lock:
            conns, self.conns = self.conns, []
        for c in conns:
            with contextlib.suppress(OSError):
                c.shutdown(socket.SHUT_RDWR)
            c.close()


def endpoint(env: str, port_env: str | None = None) -> tuple[str, int]:
    if port_env:
        return os.environ[env], int(os.environ[port_env])
    parsed = urlparse(os.environ[env])
    return parsed.hostname or "127.0.0.1", parsed.port or (443 if parsed.scheme == "https" else 80)


@contextlib.contextmanager
def app_copy(overrides: dict[str, str]) -> Iterator[str]:
    manifest_path = Path(DEPLOYED_APP) / "run.json"
    manifest = json.loads((manifest_path if manifest_path.exists() else Path("/app/run.json")).read_text())
    port = free_port()
    env = {**os.environ, "JOINERY_GRADING_KEY": GRADING_KEY, **overrides, "APP_PUBLIC_PORT": str(port)}
    log = tempfile.NamedTemporaryFile("w+", suffix=".log", delete=False)
    proc = subprocess.Popen(manifest["serve"], shell=True, cwd=DEPLOYED_APP, env=env, stdout=log,
                            stderr=subprocess.STDOUT, start_new_session=True)
    base = f"http://127.0.0.1:{port}"

    def tail() -> str:
        log.flush()
        return Path(log.name).read_text(errors="replace")[-3000:]

    try:
        deadline = time.monotonic() + BOOT_S
        up = False
        while time.monotonic() < deadline and not up:
            if proc.poll() is not None:
                pytest.fail(f"the extra app copy exited with {proc.returncode}:\n{tail()}")
            with contextlib.suppress(httpx.HTTPError):
                up = httpx.get(f"{base}/api/health", timeout=3).status_code in (200, 503)
        if not up:
            pytest.fail(f"the extra app copy never answered /api/health:\n{tail()}")
        yield base
    finally:
        with contextlib.suppress(ProcessLookupError):
            os.killpg(proc.pid, signal.SIGTERM)
        try:
            proc.wait(timeout=20)
        except subprocess.TimeoutExpired:
            with contextlib.suppress(ProcessLookupError):
                os.killpg(proc.pid, signal.SIGKILL)


