// Command zoneabbr writes web/js/lib/zoneabbr.js: for every listed zone, the tz database abbreviation used at each UTC
// offset (CDT at -300, IST at 330 ...). The browser has offsets but not abbreviations, and "Local time" shows them.
// Run from the app root after the zone list changes: go run ./cmd/zoneabbr
package main

import (
	"bufio"
	"fmt"
	"log"
	"os"
	"regexp"
	"sort"
	"strings"
	"time"
	_ "time/tzdata"
)

func main() {
	zones, err := zoneNames("zones.go")
	if err != nil {
		log.Fatalf("read zone list: %v", err)
	}
	var out strings.Builder
	out.WriteString("// Generated by cmd/zoneabbr from the tz database. Do not edit.\nexport const ZONE_ABBR = {\n")
	for _, name := range zones {
		loc, err := time.LoadLocation(name)
		if err != nil {
			log.Fatalf("load %s: %v", name, err)
		}
		byOffset := map[int]string{}
		for t := time.Date(2024, 1, 1, 0, 0, 0, 0, time.UTC); t.Year() < 2031; t = t.Add(24 * time.Hour) {
			abbr, offset := t.In(loc).Zone()
			if _, seen := byOffset[offset/60]; !seen {
				byOffset[offset/60] = abbr
			}
		}
		offsets := make([]int, 0, len(byOffset))
		for offset := range byOffset {
			offsets = append(offsets, offset)
		}
		sort.Ints(offsets)
		pairs := make([]string, 0, len(offsets))
		for _, offset := range offsets {
			pairs = append(pairs, fmt.Sprintf("\"%d\":%q", offset, byOffset[offset]))
		}
		fmt.Fprintf(&out, "  %q: {%s},\n", name, strings.Join(pairs, ","))
	}
	out.WriteString("};\n")
	if err := os.WriteFile("web/js/lib/zoneabbr.js", []byte(out.String()), 0o644); err != nil {
		log.Fatalf("write zoneabbr.js: %v", err)
	}
}

var zoneLine = regexp.MustCompile(`^\t"([^"]+)",$`)

// zoneNames reads the quoted names of the zone list in zones.go.
func zoneNames(path string) ([]string, error) {
	file, err := os.Open(path)
	if err != nil {
		return nil, fmt.Errorf("open %s: %w", path, err)
	}
	defer file.Close()
	var names []string
	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		if m := zoneLine.FindStringSubmatch(scanner.Text()); m != nil {
			names = append(names, m[1])
		}
	}
	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}
	return names, nil
}
