VISUALLY_HIDDEN_JS = """(el) => {
  const r = el.getBoundingClientRect();
  let [x0, y0, x1, y1] = [r.left, r.top, r.right, r.bottom];
  for (let n = el; n instanceof Element; n = n.parentElement) {
    const cs = getComputedStyle(n), b = n.getBoundingClientRect();
    if (parseFloat(cs.opacity) === 0 || cs.visibility === 'hidden') return true;
    const inset = /inset\\(\\s*(\\d+(?:\\.\\d+)?)%/.exec(cs.clipPath || '');
    if (inset && parseFloat(inset[1]) >= 50) return true;
    const clip = /rect\\(([^)]*)\\)/.exec(cs.clip || '');
    if (clip) {
      const [t, rt, bt, l] = clip[1].split(/[\\s,]+/).map(v => v === 'auto' ? NaN : parseFloat(v));
      if (!isNaN(t)) y0 = Math.max(y0, b.top + t);
      if (!isNaN(rt)) x1 = Math.min(x1, b.left + rt);
      if (!isNaN(bt)) y1 = Math.min(y1, b.top + bt);
      if (!isNaN(l)) x0 = Math.max(x0, b.left + l);
    }
    if (n !== el && (cs.overflowX !== 'visible' || cs.overflowY !== 'visible')) {
      x0 = Math.max(x0, b.left); y0 = Math.max(y0, b.top); x1 = Math.min(x1, b.right); y1 = Math.min(y1, b.bottom);
    }
  }
  x0 = Math.max(x0, -window.scrollX); y0 = Math.max(y0, -window.scrollY);
  return Math.max(0, x1 - x0) * Math.max(0, y1 - y0) <= 4;
}"""


