CREATE TABLE IF NOT EXISTS employer (
  id integer PRIMARY KEY,
  name text NOT NULL,
  time_zone text NOT NULL,
  seeded_on date NOT NULL
);

CREATE TABLE IF NOT EXISTS person (
  id integer PRIMARY KEY,
  employer_id integer NOT NULL REFERENCES employer (id),
  name text NOT NULL,
  work_address text NOT NULL,
  role text NOT NULL CHECK (role IN ('employee', 'manager', 'admin')),
  manager_id integer REFERENCES person (id),
  active boolean NOT NULL,
  subject text,
  phone text,
  private_note text
);
CREATE UNIQUE INDEX IF NOT EXISTS person_work_address_unique ON person (lower(normalize(work_address, NFKC)));

CREATE TABLE IF NOT EXISTS attendance_day (
  id bigserial PRIMARY KEY,
  person_id integer NOT NULL REFERENCES person (id),
  day date NOT NULL,
  recorded_in timestamptz,
  recorded_out timestamptz,
  source text NOT NULL CHECK (source IN ('clock', 'regularisation')),
  UNIQUE (person_id, day)
);

CREATE TABLE IF NOT EXISTS leave_day (
  id bigserial PRIMARY KEY,
  person_id integer NOT NULL REFERENCES person (id),
  day date NOT NULL,
  kind text NOT NULL CHECK (kind IN ('annual', 'sickness')),
  status text NOT NULL CHECK (status IN ('approved', 'pending')),
  UNIQUE (person_id, day)
);

CREATE TABLE IF NOT EXISTS regularisation_request (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id integer NOT NULL REFERENCES person (id),
  day date NOT NULL,
  correction_type text NOT NULL
    CHECK (correction_type IN ('missed_in', 'missed_out', 'offsite', 'whole_day', 'night_shift')),
  claimed_in time,
  claimed_out time,
  reason text NOT NULL,
  state text NOT NULL CHECK (state IN ('pending', 'approved', 'rejected', 'cancelled')),
  raised_at timestamptz NOT NULL,
  decided_by integer REFERENCES person (id),
  decided_at timestamptz,
  decision_note text,
  idempotency_key text,
  CHECK ((state IN ('approved', 'rejected')) = (decided_by IS NOT NULL AND decided_at IS NOT NULL)),
  CHECK (state IN ('approved', 'rejected') OR (decided_by IS NULL AND decided_at IS NULL)),
  CHECK (state <> 'rejected' OR btrim(coalesce(decision_note, '')) <> ''),
  CHECK (decided_by <> person_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS regularisation_request_one_pending
  ON regularisation_request (person_id, day) WHERE state = 'pending';
CREATE UNIQUE INDEX IF NOT EXISTS regularisation_request_idempotency_key
  ON regularisation_request (person_id, idempotency_key) WHERE idempotency_key IS NOT NULL;

CREATE TABLE IF NOT EXISTS policy (
  version integer PRIMARY KEY CHECK (version >= 1),
  employer_id integer NOT NULL REFERENCES employer (id),
  monthly_cap integer NOT NULL CHECK (monthly_cap BETWEEN 0 AND 10),
  lookback_days integer NOT NULL CHECK (lookback_days BETWEEN 1 AND 90),
  enabled_types text[] NOT NULL CHECK (cardinality(enabled_types) >= 1),
  require_note_on_approve boolean NOT NULL,
  self_approval_allowed boolean NOT NULL CHECK (NOT self_approval_allowed),
  created_by integer NOT NULL REFERENCES person (id),
  created_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS audit_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seq bigint NOT NULL UNIQUE CHECK (seq >= 1),
  request_id bigint REFERENCES regularisation_request (id),
  actor_id integer NOT NULL REFERENCES person (id),
  actor_role text NOT NULL CHECK (actor_role IN ('manager', 'admin')),
  verb text NOT NULL CHECK (verb IN ('approved', 'rejected', 'policy_saved', 'share_mint', 'share_revoke')),
  subject_type text NOT NULL CHECK (subject_type IN ('request', 'policy', 'share_link')),
  subject_id bigint NOT NULL,
  occurred_at timestamptz NOT NULL,
  note text,
  prev_hash text NOT NULL CHECK (prev_hash ~ '^[0-9a-f]{64}$'),
  entry_hash text NOT NULL CHECK (entry_hash ~ '^[0-9a-f]{64}$')
);

CREATE TABLE IF NOT EXISTS share_link (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id integer NOT NULL REFERENCES person (id),
  month text NOT NULL CHECK (month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  token_hash text NOT NULL UNIQUE,
  minted_by integer NOT NULL REFERENCES person (id),
  minted_at timestamptz NOT NULL,
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  replaced_at timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS share_link_one_live
  ON share_link (person_id, month) WHERE revoked_at IS NULL AND replaced_at IS NULL;
CREATE INDEX IF NOT EXISTS share_link_by_minter ON share_link (minted_by, minted_at);

CREATE TABLE IF NOT EXISTS sign_in_attempt (
  id bigserial PRIMARY KEY,
  work_address text NOT NULL,
  attempted_at timestamptz NOT NULL,
  succeeded boolean NOT NULL
);
CREATE INDEX IF NOT EXISTS sign_in_attempt_by_address ON sign_in_attempt (work_address, attempted_at);

CREATE TABLE IF NOT EXISTS sign_in_lock (
  work_address text PRIMARY KEY,
  locked_until timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS desk_session (
  id bigserial PRIMARY KEY,
  token_hash text NOT NULL UNIQUE,
  person_id integer NOT NULL REFERENCES person (id),
  began_at timestamptz NOT NULL,
  last_used_at timestamptz NOT NULL,
  ended_at timestamptz,
  replaced_at timestamptz
);

CREATE OR REPLACE FUNCTION audit_event_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'audit_event is append-only';
END;
$$;
CREATE OR REPLACE TRIGGER audit_event_no_change BEFORE UPDATE OR DELETE ON audit_event
  FOR EACH ROW EXECUTE FUNCTION audit_event_append_only();
CREATE OR REPLACE TRIGGER audit_event_no_truncate BEFORE TRUNCATE ON audit_event
  FOR EACH STATEMENT EXECUTE FUNCTION audit_event_append_only();
REVOKE UPDATE, DELETE, TRUNCATE ON audit_event FROM CURRENT_USER;
