const index: Record<Lang, number> = { en: 0, de: 1, ar: 2 }

function lookup(lang: Lang, key: MessageKey): string {
  const row = table[key]
  if (!row) throw new Error(`missing message ${key}`)
  return row[index[lang]]
}

export function countedPhrase(lang: Lang, noun: string, n: number): string {
  const category = new Intl.PluralRules(LOCALES[lang]).select(n)
  const forms = counted[noun][lang]
  return (forms[category] ?? forms.other ?? '').replace('{n}', String(n))
}

export type Params = Record<string, string | number>

/** Messages worded differently when their count is exactly one: the count parameter and the one-form triple. */
const singular: Record<string, { count: string; text: Triple }> = {
  'problems.heading': { count: 'count:problem', text: T('There is 1 problem', 'Es gibt 1 Problem', 'توجد مشكلة واحدة') },
}

export function t(lang: Lang, key: MessageKey, params: Params = {}): string {
  const one = singular[key]
  const template = one && params[one.count] === 1 ? one.text[index[lang]] : lookup(lang, key)
  return template.replace(/\{([^}]+)\}/g, (whole, name: string) => {
    if (name.startsWith('count:')) return countedPhrase(lang, name.slice(6), Number(params[name]))
    if (name === 'currency words') return CURRENCY_WORDS[params[name] as Currency][index[lang]]
    const value = params[name]
    return value === undefined ? whole : String(value)
  })
}

/** Adds strings the brief's tables do not carry (page-local copy); keys must start with `x.`. */
export function extendMessages(extra: Record<string, readonly [string, string, string]>): void {
  for (const [key, value] of Object.entries(extra)) {
    if (!key.startsWith('x.')) throw new Error(`extra message ${key} must start with x.`)
    table[key] = value
  }
}
