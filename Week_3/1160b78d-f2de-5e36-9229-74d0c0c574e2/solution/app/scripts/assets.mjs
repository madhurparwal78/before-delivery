// Writes assets.json: the sha256, source and licence of every binary asset in the built tree.
// Run it after a build: node scripts/assets.mjs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { FONTS } from "./fonts.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sha = (path) => createHash("sha256").update(readFileSync(join(root, path))).digest("hex");

const assets = ["dusk", "night", "signin"].map((name) => ({
  path: `web/img/${name}.jpg`,
  sha256: sha(`web/img/${name}.jpg`),
  source: "generated by cmd/plates, a seeded procedural renderer run during build",
  licence: "original",
}));

for (const { pkg, files } of FONTS) {
  const { version } = JSON.parse(readFileSync(join(root, "node_modules", pkg, "package.json"), "utf8"));
  for (const file of files) {
    assets.push({
      path: `web/fonts/${file}.woff2`,
      sha256: sha(`web/fonts/${file}.woff2`),
      source: `npm ${pkg} ${version}, files/${file}.woff2`,
      licence: "OFL-1.1",
    });
  }
}

writeFileSync(join(root, "assets.json"), `${JSON.stringify(assets, null, 2)}\n`);
