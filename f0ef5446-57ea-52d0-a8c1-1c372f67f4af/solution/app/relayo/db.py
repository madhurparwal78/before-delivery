"""PostgreSQL access: a small pg8000 connection pool, transactions and the schema."""

from __future__ import annotations

import queue
from collections.abc import Iterator
from contextlib import contextmanager
from typing import Any
from urllib.parse import unquote, urlsplit

import pg8000.native
from pg8000.exceptions import DatabaseError, InterfaceError

from .config import settings

Connection = pg8000.native.Connection


class DatabaseUnavailable(Exception):
    """PostgreSQL cannot be reached or dropped the connection."""


class Pool:
    def __init__(self, url: str, size: int = 24) -> None:
        self._url = url
        self._idle: queue.LifoQueue[Connection] = queue.LifoQueue(maxsize=size)

    def _connect(self) -> Connection:
        parts = urlsplit(self._url)
        address = {key: value for key, value in (("host", parts.hostname), ("port", parts.port)) if value}
        try:
            return pg8000.native.Connection(
                user=unquote(parts.username or ""),
                password=unquote(parts.password or ""),
                database=unquote(parts.path.lstrip("/")),
                timeout=15,
                application_name="relayo",
                **address,
            )
        except (InterfaceError, DatabaseError, OSError) as error:
            raise DatabaseUnavailable(str(error)) from error

    @contextmanager
    def connection(self) -> Iterator[Connection]:
        try:
            conn = self._idle.get_nowait()
        except queue.Empty:
            conn = self._connect()
        reusable = False
        try:
            yield conn
            reusable = True
        except DatabaseError:
            reusable = True
            raise
        except (InterfaceError, OSError) as error:
            raise DatabaseUnavailable(str(error)) from error
        finally:
            if reusable:
                try:
                    self._idle.put_nowait(conn)
                except queue.Full:
                    conn.close()
            else:
                _discard(conn)


def _discard(conn: Connection) -> None:
    try:
        conn.close()
    except (InterfaceError, OSError):
        pass


pool = Pool(settings.database_url)


def rows(conn: Connection, sql: str, **params: Any) -> list[dict[str, Any]]:
    found = conn.run(sql, **params)
    names = [column["name"] for column in conn.columns or []]
    return [dict(zip(names, row, strict=True)) for row in found or []]


def one(conn: Connection, sql: str, **params: Any) -> dict[str, Any] | None:
    found = rows(conn, sql, **params)
    return found[0] if found else None


connection = pool.connection


@contextmanager
def transaction(isolation: str = "") -> Iterator[Connection]:
    with pool.connection() as conn:
        conn.run(f"BEGIN ISOLATION LEVEL {isolation}" if isolation else "BEGIN")
        try:
            yield conn
        except BaseException:
            conn.run("ROLLBACK")
            raise
        conn.run("COMMIT")


SCHEMA = """
CREATE TABLE IF NOT EXISTS partner_applications (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name text NOT NULL,
    last_name text NOT NULL,
    work_email text NOT NULL,
    job_title text NOT NULL,
    company_name text NOT NULL,
    website text NOT NULL,
    company_type text NOT NULL,
    employee_band text NOT NULL,
    markets jsonb NOT NULL,
    customer_segment text NOT NULL,
    partnership_interests jsonb NOT NULL,
    goals text NOT NULL,
    consent boolean NOT NULL,
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    reviewer text,
    decision_note text,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    decided_at timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS partner_applications_work_email_key
    ON partner_applications (work_email COLLATE "C");
CREATE INDEX IF NOT EXISTS partner_applications_status_created
    ON partner_applications (status, created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS outbound_emails (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id integer NOT NULL REFERENCES partner_applications (id),
    kind text NOT NULL CHECK (kind IN ('receipt', 'approved', 'rejected')),
    recipient text NOT NULL,
    subject text NOT NULL,
    body text NOT NULL,
    status text NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'sent')),
    attempts integer NOT NULL DEFAULT 0,
    last_attempt_at timestamptz,
    next_attempt_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    sent_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (application_id, kind)
);
CREATE INDEX IF NOT EXISTS outbound_emails_due ON outbound_emails (next_attempt_at, id) WHERE status = 'queued';

CREATE TABLE IF NOT EXISTS sign_in_failures (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_key text NOT NULL,
    failed_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX IF NOT EXISTS sign_in_failures_key ON sign_in_failures (email_key, failed_at);

CREATE TABLE IF NOT EXISTS idempotency_keys (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key text NOT NULL UNIQUE,
    body_hash text NOT NULL,
    state text NOT NULL CHECK (state IN ('in_progress', 'done')),
    response_status integer,
    response_body text,
    first_used_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS ended_sessions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sid text NOT NULL UNIQUE,
    ended_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE IF NOT EXISTS integrations (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug text NOT NULL UNIQUE,
    name text NOT NULL,
    description text NOT NULL,
    category text NOT NULL,
    icon_ref text NOT NULL,
    published boolean NOT NULL
);

CREATE TABLE IF NOT EXISTS articles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug text NOT NULL UNIQUE,
    title text NOT NULL,
    category text NOT NULL,
    summary text NOT NULL,
    author text NOT NULL,
    read_time integer NOT NULL,
    cover_ref text NOT NULL,
    body text NOT NULL,
    published_at timestamptz NOT NULL,
    published boolean NOT NULL
);
CREATE INDEX IF NOT EXISTS articles_order ON articles (published_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS press_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date date NOT NULL,
    category text NOT NULL CHECK (category IN ('News', 'Press Releases')),
    headline text NOT NULL,
    link text NOT NULL,
    published boolean NOT NULL,
    UNIQUE (headline, date)
);
CREATE INDEX IF NOT EXISTS press_items_order ON press_items (date DESC, id DESC);

CREATE TABLE IF NOT EXISTS jobs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL UNIQUE,
    location text NOT NULL,
    is_open boolean NOT NULL
);

CREATE TABLE IF NOT EXISTS resource_cards (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    block text NOT NULL,
    category text NOT NULL,
    title text NOT NULL UNIQUE,
    date date NOT NULL,
    summary text NOT NULL,
    target_link text NOT NULL,
    published boolean NOT NULL
);
"""


def create_schema(conn: Connection) -> None:
    for statement in SCHEMA.split(";"):
        if statement.strip():
            conn.run(statement)
