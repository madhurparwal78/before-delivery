_B_ANIM_REC_JS = r"""
() => {
  if (window.__bRec) return true;
  const rec = {list: [], seen: new WeakSet()};
  window.__bRec = rec;
  rec.scan = () => {
    for (const a of document.getAnimations()) {
      if (rec.seen.has(a)) continue;
      rec.seen.add(a);
      const eff = a.effect;
      if (!eff || !eff.getComputedTiming) continue;
      let props = [];
      try { props = Array.from(new Set(eff.getKeyframes().flatMap(k => Object.keys(k))))
              .filter(p => !['offset', 'computedOffset', 'easing', 'composite'].includes(p)); } catch (e) {}
      if (a.transitionProperty) props.push(a.transitionProperty);
      rec.list.push({target: eff.target || null, props, duration: Number(eff.getComputedTiming().duration) || 0});
    }
  };
  new MutationObserver(() => rec.scan()).observe(document.documentElement,
    {subtree: true, childList: true, attributes: true});
  const orig = Element.prototype.animate;
  Element.prototype.animate = function (...args) { const a = orig.apply(this, args); rec.scan(); return a; };
  return true;
}
"""

