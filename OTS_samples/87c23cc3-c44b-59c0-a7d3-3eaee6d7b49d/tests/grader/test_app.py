def watch(page: Page, total_ms: int, step_ms: int = 10) -> None:
    elapsed = 0
    while elapsed < total_ms:
        advance(page, step_ms)
        elapsed += step_ms
        page.evaluate("() => window.__rec && window.__rec.scan()")


@contextlib.contextmanager
def browse(browser: Browser, base: str, path: str, sess: str | None = None, *, reduced: bool = False,
           size: tuple[int, int] = DESKTOP) -> Iterator[Page]:
    with open_app(browser, f"{base}/api/health", reduced_motion="reduce" if reduced else "no-preference") as page:
        page.set_viewport_size({"width": size[0], "height": size[1]})
        if sess:
            page.context.add_cookies([{"name": "joinery_session", "value": sess, "url": base}])
        page.goto(f"{base}{path}")
        page.evaluate(STAY_JS)
        yield page


