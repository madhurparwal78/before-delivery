def _d_press(loc: Locator, key: str = "Enter") -> None:
    loc.first.focus()
    loc.page.keyboard.press(key)


def _d_focused(loc: Locator) -> bool:
    return bool(loc.count()) and bool(loc.first.evaluate(FOCUS_INSIDE_JS))


def _d_tick(*pages: Page) -> bool:
    for p in pages:
        advance(p, _D_VIEWER_TICK_MS)
    return True


