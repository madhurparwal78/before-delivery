// Tables of the sheet side: sheets, viewports, versions with their review steps and stamps, markups, issues, RFIs, view links,
// export jobs and parsed imports. Underlay records live in the drawing's own `underlays` column.
import { registerSchemaPart } from './registry.ts';

const STATEMENTS = [
  `CREATE TABLE IF NOT EXISTS sheets (
    id text PRIMARY KEY,
    drawing_id text NOT NULL REFERENCES drawings(id) ON DELETE CASCADE,
    number integer NOT NULL,
    name text NOT NULL,
    size text NOT NULL,
    locked boolean NOT NULL DEFAULT false,
    locked_by text,
    creator text NOT NULL,
    attributes jsonb NOT NULL DEFAULT '{}',
    UNIQUE (drawing_id, number))`,
  `CREATE TABLE IF NOT EXISTS viewports (
    id text PRIMARY KEY,
    sheet_id text NOT NULL REFERENCES sheets(id) ON DELETE CASCADE,
    seq bigserial NOT NULL,
    x double precision NOT NULL,
    y double precision NOT NULL,
    width double precision NOT NULL,
    height double precision NOT NULL,
    scale text NOT NULL,
    view_x double precision NOT NULL,
    view_y double precision NOT NULL,
    frozen_layers jsonb NOT NULL)`,
  `CREATE INDEX IF NOT EXISTS viewports_sheet ON viewports (sheet_id, seq)`,
  // seq orders the versions of all sheets of a drawing; the snapshot is the cache that keeps old versions open while storage is down.
  `CREATE TABLE IF NOT EXISTS versions (
    id text PRIMARY KEY,
    sheet_id text NOT NULL REFERENCES sheets(id) ON DELETE CASCADE,
    seq bigserial NOT NULL,
    number integer NOT NULL,
    state text NOT NULL,
    replaced_by text REFERENCES versions(id) DEFERRABLE INITIALLY DEFERRED,
    snapshot jsonb NOT NULL,
    steps jsonb NOT NULL DEFAULT '[]',
    stamps jsonb NOT NULL DEFAULT '[]',
    UNIQUE (sheet_id, number))`,
  `CREATE TABLE IF NOT EXISTS markups (
    id text PRIMARY KEY,
    version_id text NOT NULL REFERENCES versions(id) ON DELETE CASCADE,
    seq bigserial NOT NULL,
    kind text NOT NULL,
    x1 double precision NOT NULL,
    y1 double precision NOT NULL,
    x2 double precision NOT NULL,
    y2 double precision NOT NULL,
    text text NOT NULL,
    flag text,
    author text NOT NULL)`,
  `CREATE INDEX IF NOT EXISTS markups_version ON markups (version_id, seq)`,
  `CREATE TABLE IF NOT EXISTS issues (
    id text PRIMARY KEY,
    version_id text NOT NULL REFERENCES versions(id) ON DELETE CASCADE,
    seq bigserial NOT NULL,
    title text NOT NULL,
    x double precision NOT NULL,
    y double precision NOT NULL,
    state text NOT NULL,
    creator text NOT NULL)`,
  `CREATE INDEX IF NOT EXISTS issues_version ON issues (version_id, seq)`,
  `CREATE TABLE IF NOT EXISTS rfis (
    id text PRIMARY KEY,
    issue_id text NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
    seq bigserial NOT NULL,
    question text NOT NULL,
    answer text,
    state text NOT NULL,
    asker text NOT NULL,
    addressee text NOT NULL,
    ball_in_court text NOT NULL)`,
  `CREATE INDEX IF NOT EXISTS rfis_issue ON rfis (issue_id, seq)`,
  `CREATE TABLE IF NOT EXISTS links (
    id text PRIMARY KEY,
    token text NOT NULL UNIQUE,
    version_id text NOT NULL REFERENCES versions(id) ON DELETE CASCADE,
    created_by text NOT NULL,
    expires_at timestamptz NOT NULL,
    revoked boolean NOT NULL DEFAULT false)`,
  `CREATE TABLE IF NOT EXISTS export_jobs (
    id text PRIMARY KEY,
    drawing_id text NOT NULL REFERENCES drawings(id) ON DELETE CASCADE,
    format text NOT NULL,
    state text NOT NULL,
    progress integer NOT NULL,
    username text NOT NULL,
    next_step_at timestamptz)`,
  `CREATE TABLE IF NOT EXISTS imports (
    id text PRIMARY KEY,
    drawing_id text NOT NULL REFERENCES drawings(id) ON DELETE CASCADE,
    key text NOT NULL,
    parsed jsonb NOT NULL)`,
];

for (const statement of STATEMENTS) registerSchemaPart(statement);
