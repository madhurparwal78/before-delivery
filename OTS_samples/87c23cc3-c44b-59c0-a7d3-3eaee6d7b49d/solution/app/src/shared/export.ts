import type { Dialect } from './domain.ts'
import { foreignColumn } from './diagram.ts'
import { findColumn, findEntity, type Choice, type Column, type Entity, type Link, type Literal, type Model } from './mortise.ts'
import { sha256Hex } from './sha256.ts'

const IDENTIFIER_LIMIT: Record<Dialect, number> = { postgresql: 63, mysql: 64 }
const DIALECT_NAME: Record<Dialect, string> = { postgresql: 'PostgreSQL', mysql: 'MySQL' }

const POSTGRES_TYPES: Record<string, string> = {
  int: 'INTEGER', smallint: 'SMALLINT', bigint: 'BIGINT', float: 'REAL', double: 'DOUBLE PRECISION', bool: 'BOOLEAN', text: 'TEXT',
  date: 'DATE', time: 'TIME', timestamp: 'TIMESTAMP', timestamptz: 'TIMESTAMPTZ', uuid: 'UUID', json: 'JSONB', bytes: 'BYTEA',
}
const MYSQL_TYPES: Record<string, string> = {
  int: 'INT', smallint: 'SMALLINT', bigint: 'BIGINT', float: 'FLOAT', double: 'DOUBLE', bool: 'BOOLEAN', text: 'TEXT', date: 'DATE',
  time: 'TIME', timestamp: 'DATETIME', timestamptz: 'TIMESTAMP', uuid: 'CHAR(36)', json: 'JSON', bytes: 'LONGBLOB',
}

interface ForeignKey {
  table: Entity
  column: Column
  target: { table: Entity; column: Column }
  link: Link
}

class Exporter {
  private readonly notes = new Set<string>()
  private readonly choices: Map<string, Choice>

  constructor(
    private readonly model: Model,
    private readonly dialect: Dialect,
  ) {
    this.choices = new Map(model.choices.map((choice) => [choice.name, choice]))
  }

  private quote(identifier: string): string {
    return this.dialect === 'postgresql' ? `"${identifier}"` : `\`${identifier}\``
  }

  /** Quotes an identifier, shortening it to the dialect's limit and noting the change. */
  private ident(identifier: string): string {
    const limit = IDENTIFIER_LIMIT[this.dialect]
    if (identifier.length <= limit) return this.quote(identifier)
    const short = `${identifier.slice(0, limit - 9)}_${sha256Hex(identifier).slice(0, 8)}`
    this.notes.add(`identifier ${identifier} shortened to ${short}`)
    return this.quote(short)
  }

  private literal(literal: Literal): string {
    switch (literal.kind) {
      case 'string':
        return `'${literal.text.replaceAll("'", "''")}'`
      case 'number':
        return literal.text
      case 'boolean':
        return literal.text.toUpperCase()
      case 'null':
        return 'NULL'
      case 'now':
        return 'CURRENT_TIMESTAMP'
    }
  }

  private columnType(entity: Entity, column: Column): string {
    const choice = this.choices.get(column.type.name)
    if (choice) {
      if (this.dialect === 'postgresql') return this.ident(choice.name)
      this.notes.add(`choice ${choice.name} inlined as ENUM on ${entity.name}.${column.name}`)
      return `ENUM(${choice.values.map((value) => `'${value.replaceAll("'", "''")}'`).join(', ')})`
    }
    const name = column.type.name
    if (name === 'decimal') return `${this.dialect === 'postgresql' ? 'NUMERIC' : 'DECIMAL'}(${column.type.params.join(',')})`
    if (name === 'varchar' || name === 'char') return `${name.toUpperCase()}(${column.type.params[0]})`
    if (this.dialect === 'mysql' && name === 'uuid') this.notes.add(`uuid column ${entity.name}.${column.name} stored as CHAR(36)`)
    if (this.dialect === 'mysql' && name === 'timestamptz') this.notes.add(`timestamptz column ${entity.name}.${column.name} stored as TIMESTAMP`)
    return (this.dialect === 'postgresql' ? POSTGRES_TYPES : MYSQL_TYPES)[name] as string
  }

  private columnLine(entity: Entity, column: Column): string {
    let line = `${this.ident(column.name)} ${this.columnType(entity, column)}`
    if (column.required || column.key) line += ' NOT NULL'
    if (column.auto) line += this.dialect === 'postgresql' ? ' GENERATED BY DEFAULT AS IDENTITY' : ' AUTO_INCREMENT'
    if (column.default) line += ` DEFAULT ${this.literal(column.default)}`
    return line
  }

  private foreignKeys(): ForeignKey[] {
    const keys: ForeignKey[] = []
    for (const link of this.model.links) {
      const side = foreignColumn(link)
      if (!side) {
        this.notes.add(`many-to-many link ${link.from.entity}.${link.from.column} >-< ${link.to.entity}.${link.to.column} has no foreign key`)
        continue
      }
      const other = side === link.from ? link.to : link.from
      const table = findEntity(this.model, side.entity) as Entity
      const target = findEntity(this.model, other.entity) as Entity
      keys.push({
        table,
        column: findColumn(table, side.column) as Column,
        target: { table: target, column: findColumn(target, other.column) as Column },
        link,
      })
    }
    return keys
  }

  private foreignKeyCell(key: ForeignKey): string {
    const name = this.ident(`${key.table.name}_${key.column.name}_fkey`)
    const action = key.link.deleteAction ? ` ON DELETE ${key.link.deleteAction.toUpperCase()}` : ''
    return `CONSTRAINT ${name} FOREIGN KEY (${this.ident(key.column.name)}) REFERENCES ${this.ident(key.target.table.name)} (${this.ident(key.target.column.name)})${action}`
  }

  private creationOrder(keys: ForeignKey[]): Entity[] {
    const remaining = [...this.model.entities].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
    const created: Entity[] = []
    const createdNames = new Set<string>()
    while (remaining.length) {
      const ready = remaining.find((table) =>
        keys.every((key) => key.table !== table || key.target.table === table || createdNames.has(key.target.table.name)),
      )
      const next = ready ?? (remaining[0] as Entity)
      remaining.splice(remaining.indexOf(next), 1)
      created.push(next)
      createdNames.add(next.name)
    }
    return created
  }

  private createTable(table: Entity, inline: ForeignKey[]): string {
    const items = table.columns.map((column) => this.columnLine(table, column))
    const primary = table.columns.filter((column) => column.key)
    if (primary.length) {
      const names = primary.map((column) => this.ident(column.name)).join(', ')
      items.push(this.dialect === 'postgresql' ? `CONSTRAINT ${this.ident(`${table.name}_pkey`)} PRIMARY KEY (${names})` : `PRIMARY KEY (${names})`)
    }
    for (const column of table.columns) {
      if (!column.unique) continue
      const name = this.ident(`${table.name}_${column.name}_key`)
      const columnName = this.ident(column.name)
      items.push(this.dialect === 'postgresql' ? `CONSTRAINT ${name} UNIQUE (${columnName})` : `UNIQUE KEY ${name} (${columnName})`)
    }
    for (const key of inline) items.push(this.foreignKeyCell(key))
    return `CREATE TABLE ${this.ident(table.name)} (\n${items.map((item) => `  ${item}`).join(',\n')}\n)`
  }

  statements(): string[] {
    const statements: string[] = []
    if (this.dialect === 'postgresql') {
      const ordered = [...this.model.choices].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
      for (const choice of ordered) {
        statements.push(`CREATE TYPE ${this.ident(choice.name)} AS ENUM (${choice.values.map((value) => `'${value.replaceAll("'", "''")}'`).join(', ')})`)
      }
    }
    const keys = this.foreignKeys()
    const order = this.creationOrder(keys)
    const position = new Map(order.map((table, i) => [table.name, i]))
    const deferred: ForeignKey[] = []
    for (const table of order) {
      const inline: ForeignKey[] = []
      for (const key of keys.filter((candidate) => candidate.table === table)) {
        const targetAt = position.get(key.target.table.name) as number
        if (targetAt <= (position.get(table.name) as number)) inline.push(key)
        else deferred.push(key)
      }
      statements.push(this.createTable(table, inline))
    }
    deferred.sort((a, b) => {
      const byTable = (position.get(a.table.name) as number) - (position.get(b.table.name) as number)
      if (byTable) return byTable
      const left = `${a.table.name}_${a.column.name}_fkey`
      const right = `${b.table.name}_${b.column.name}_fkey`
      return left < right ? -1 : left > right ? 1 : 0
    })
    for (const key of deferred) statements.push(`ALTER TABLE ${this.ident(key.table.name)} ADD ${this.foreignKeyCell(key)}`)
    for (const table of order) {
      for (const index of table.indexes) {
        const name = index.name ?? `${table.name}_${index.columns.join('_')}_idx`
        const columns = index.columns.map((column) => this.ident(column)).join(', ')
        statements.push(`CREATE ${index.unique ? 'UNIQUE ' : ''}INDEX ${this.ident(name)} ON ${this.ident(table.name)} (${columns})`)
      }
    }
    return statements
  }

  noteLines(): string[] {
    return [...this.notes].sort().map((note) => `-- note: ${note}`)
  }
}

/** The DDL file for a valid model. The same model always gives the same bytes. */
export function exportDdl(model: Model, dialect: Dialect): string {
  const exporter = new Exporter(model, dialect)
  const statements = exporter.statements()
  const head = [`-- Joinery export: ${DIALECT_NAME[dialect]}`, ...exporter.noteLines()].join('\n')
  return statements.length ? `${head}\n\n${statements.map((statement) => `${statement};`).join('\n\n')}\n` : `${head}\n`
}
