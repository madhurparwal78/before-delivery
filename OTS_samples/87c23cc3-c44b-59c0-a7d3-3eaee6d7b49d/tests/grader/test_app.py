def shorten(identifier: str, limit: int) -> str:
    if len(identifier) <= limit:
        return identifier
    return identifier[: limit - 9] + "_" + hashlib.sha256(identifier.encode()).hexdigest()[:8]


def api(base: str, method: str, path: str, sess: str | None = None, **kw: Any) -> httpx.Response:
    cookies = {"joinery_session": sess} if sess else {}
    with httpx.Client(base_url=base, timeout=HTTP_TIMEOUT_S, cookies=cookies, follow_redirects=False) as c:
        return c.request(method, path, **kw)


def err_ok(resp: httpx.Response, status: int, body: dict | None = None, error: str | None = None) -> dict:
    assert resp.status_code == status, f"expected {status}, got {resp.status_code}: {resp.text[:400]}"
    data = resp.json()
    assert isinstance(data.get("error"), str) and isinstance(data.get("message"), str), data
    if body is not None:
        for key, value in body.items():
            assert data.get(key) == value, f"{key}: {data.get(key)!r} != {value!r}"
    if error is not None:
        assert data["error"] == error, data
    return data


def field_messages(resp: httpx.Response) -> list[str]:
    data = err_ok(resp, 422, error="invalid")
    fields = data.get("fields") or {}
    return [str(v) for v in fields.values()]


@dataclass
class World:
    base: str
    project: str
    users: dict
    shares: dict
    versions: list

    def sess(self, ref: str = "owner") -> str:
        return self.users[ref]["session"]

    def path(self, tail: str = "") -> str:
        return f"/api/projects/{self.project}{tail}"


def seed(base: str, text: str = "", layout: dict | None = None, *, name: str = PROJECT,
         versions: tuple | list = (), people: tuple | list = (), shares: tuple | list = ()) -> World:
    users = [{"ref": "owner", "email": fresh_email("owner"), "displayName": OWNER_NAME}]
    names = {"owner": OWNER_NAME}
    members = []
    for ref, display, role in people:
        users.append({"ref": ref, "email": fresh_email(ref), "displayName": display})
        names[ref] = display
        if role:
            members.append({"user": ref, "role": role})
    project = {"ref": "p1", "owner": "owner", "name": name, "text": text,
               "layout": layout if layout is not None else {"entities": {}, "groups": {}},
               "versions": list(versions), "members": members, "shares": list(shares)}
    resp = httpx.post(f"{base}/api/grading/setup", json={"users": users, "projects": [project]},
                      headers={"X-Grading-Key": GRADING_KEY}, timeout=HTTP_TIMEOUT_S)
    assert resp.status_code == 201, f"POST /api/grading/setup answered {resp.status_code}: {resp.text[:500]}"
    body = resp.json()
    out = {}
    for u in users:
        got = body["users"][u["ref"]]
        out[u["ref"]] = {"id": got["id"], "session": got["session"], "email": u["email"], "name": names[u["ref"]]}
    proj = body["projects"]["p1"]
    return World(base, proj["id"], out, body.get("shares") or {}, proj.get("versions") or [])


def project_json(w: World, ref: str = "owner") -> dict:
    resp = api(w.base, "GET", w.path(), w.sess(ref))
    assert resp.status_code == 200, resp.text[:300]
    return resp.json()


def post_edit(w: World, text: str, base: int | None = None, ref: str = "owner") -> httpx.Response:
    if base is None:
        base = project_json(w, ref)["revision"]
    return api(w.base, "POST", w.path("/edits"), w.sess(ref), json={"baseRevision": base, "text": text})


