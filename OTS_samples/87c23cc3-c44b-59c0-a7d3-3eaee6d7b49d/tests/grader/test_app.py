def _b_canvas_point(page: Page) -> tuple[float, float]:
    box = diagram(page).first.bounding_box()
    assert box, 'region "Diagram" has a box'
    height = page.viewport_size["height"]
    top, bottom = box["y"] + _B_CANVAS_MARGIN, min(box["y"] + box["height"], height) - _B_CANVAS_MARGIN
    blocked = _b_blocked_boxes(page)
    m = _B_CANVAS_MARGIN

    def free(px: float, py: float) -> bool:
        if any(b["x"] - m <= px <= b["x"] + b["width"] + m and b["y"] - m <= py <= b["y"] + b["height"] + m for b in blocked):
            return False
        return bool(diagram(page).first.evaluate(_B_HIT_INSIDE_JS, [px, py]))

    x = box["x"] + box["width"] / 2
    for frac in _B_FRACTIONS:
        y = top + (bottom - top) * frac
        spread = (-_B_PINCH_TO, -_B_PINCH_FROM, 0, _B_PINCH_FROM, _B_PINCH_TO)
        if all(free(x + dx, y) for dx in spread):
            return x, y
    pytest.fail('region "Diagram" shows no empty canvas to pinch and pan on')


