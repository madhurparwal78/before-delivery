@pytest.mark.parametrize("mode", MOTION_MODES, ids=MOTION_MODES)
def test_wf_draw_link_writeback_motion(browser: Browser, app_url: str, mode: str) -> None:
    reduced = mode == "reduced_motion"
    line = "link books.author_id >- authors.id"
    w = seed(app_url, TWO_TABLES)
    with browse(browser, app_url, f"/projects/{w.project}", w.sess(), reduced=reduced) as page:
        editor(page)
        eventually(page, lambda: ent(page, "books").count() == 1, "the diagram is drawn")
        page.evaluate(RECORDER_JS)
        keyboard_link_start(page)
        page.keyboard.press("l")
        page.keyboard.press("Tab")
        page.keyboard.press("Enter")
        seen: list[tuple[int, int]] = []
        fake = 0
        deadline = time.monotonic() + WAIT_S
        while time.monotonic() < deadline:
            last = editor_text(page).split("\n")[-1]
            k = len(last) if last and line.startswith(last) else 0
            if k:
                seen.append((fake, k))
            if k == len(line):
                break
            advance(page, CHAR_MS)
            fake += CHAR_MS
        assert seen and seen[-1][1] == len(line), "the whole link line is typed into the editor"
        watch(page, 1500)
        log = motion_log(page)
        ref = "books.author_id->authors.id"
        link_anims = [a for a in log["anims"] if a["link"] == ref and a["duration"] > 0]
        draw_marks = [m for m in log["motions"] if m["link"] == ref and m["attr"] == "data-motion" and m["value"] == "draw"]
        if reduced:
            assert seen[0][1] == len(line), f"the line appears in one step: {seen[:3]}"
            assert not draw_marks and not link_anims, "the connector appears fully drawn"
            return
        t0, k0 = seen[0]
        assert k0 < len(line), "the line is typed character by character"
        per_char = (seen[-1][0] - t0) / (len(line) - k0)
        assert abs(per_char - CHAR_MS) <= CHAR_TOLERANCE_MS, f"{per_char:.1f} ms per character"
        assert draw_marks, 'the link carries data-motion="draw" while it draws'
        assert any(DRAW_MIN_MS <= a["duration"] <= DRAW_MAX_MS for a in link_anims), link_anims
        for column in ("books.author_id", "authors.id"):
            marks = [m for m in log["motions"] if m["column"] == column and m["attr"] == "data-flash"]
            assert any(m["value"] == "true" for m in marks), f"{column} flashes"
            anims = [a for a in log["anims"] if a["column"] == column and FLASH_MIN_MS <= a["duration"] <= FLASH_MAX_MS]
            on = next((m["at"] for m in marks if m["value"] == "true"), None)
            off = next((m["at"] for m in marks if m["value"] != "true" and on is not None and m["at"] > on), None)
            span_ok = on is not None and off is not None and FLASH_MIN_MS <= off - on <= FLASH_MAX_MS
            assert anims or span_ok, f"{column} flash lasts 550-650 ms"


