_C_TAB_LIMIT = 12
_C_FILL_SHARE = 0.8
_C_ERROR_LINE = re.compile(r"Line (\d+), column (\d+): (.+)")


def _c_present(loc: Locator) -> bool:
    return loc.count() >= 1 and loc.first.is_visible()


def _c_focused(loc: Locator) -> bool:
    return loc.count() >= 1 and bool(loc.first.evaluate("e => e === document.activeElement"))


def _c_focus_inside(loc: Locator) -> bool:
    return loc.count() >= 1 and bool(loc.first.evaluate(FOCUS_INSIDE_JS))


def _c_tab_to(page: Page, scope: Locator, target: Locator, what: str) -> None:
    for _ in range(_C_TAB_LIMIT):
        if _c_focused(target):
            return
        page.keyboard.press("Tab")
        assert _c_focus_inside(scope), f"Tab left the open dialog or panel while reaching {what} (L303, L375)"
    if not _c_focused(target):
        pytest.fail(f"Tab never reached {what} within {_C_TAB_LIMIT} presses")


def _c_chip(page: Page, name: str) -> Locator:
    return page.get_by_role("toolbar", name="Editor tools", exact=True).get_by_role("button", name=name, exact=True)


def _c_export_keys(w: World, dialect: str) -> list[str]:
    return [k for k in S3().keys(f"exports/{w.project}/") if k.endswith(f"-{dialect}.sql")]


def _c_error_at(items: list[str], line: int, message: str) -> bool:
    for item in items:
        found = _C_ERROR_LINE.fullmatch(item)
        if found and int(found.group(1)) == line and found.group(3) == message:
            return True
    return False


def _c_version_numbers(w: World) -> list[int]:
    return [v["number"] for v in api(w.base, "GET", w.path("/versions"), w.sess()).json()["versions"]]


def _c_open_import(page: Page, dialect_label: str) -> Locator:
    _c_chip(page, "Import").click()
