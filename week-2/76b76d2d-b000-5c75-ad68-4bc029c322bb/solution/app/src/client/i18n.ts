/** `<date>` and `<time>` from an API instant, which is already America/Toronto local with its offset. */
export function localDate(instant: string): string {
  return instant.slice(0, 10);
}
export function localTime(instant: string): string {
  return instant.slice(11, 16);
}

/** Dollars typed by a person ("12.34", "12,34", "600") to integer cents, or null when it is not an amount. */
export function dollarsToCents(text: string): number | null {
  const match = /^\s*(\d{1,7})(?:[.,](\d{1,2}))?\s*\$?\s*$/.exec(text);
  if (!match) return null;
  return Number(match[1]) * 100 + Number((match[2] ?? "0").padEnd(2, "0"));
}
